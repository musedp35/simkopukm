USE simkopukm;

-- ==================== MASTER TABLES ====================

CREATE TABLE IF NOT EXISTS ma_user (
    MEMBER_REGISTRY VARCHAR(50) PRIMARY KEY,
    ROLE_ID VARCHAR(10),
    USERNAME VARCHAR(100),
    USER_STATUS INT DEFAULT 1,
    PASSWORD VARCHAR(255),
    UPDATE_BY VARCHAR(100),
    LOGTIME DATETIME,
    last_login DATETIME
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_role (
    ROLE_ID VARCHAR(10) PRIMARY KEY,
    ROLE_NAME VARCHAR(100),
    NOTES TEXT,
    MODULE_ID VARCHAR(10),
    UPDATE_BY VARCHAR(100),
    LOGTIME DATETIME
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_module (
    MODULE_ID VARCHAR(10) PRIMARY KEY,
    MODULE_NAME VARCHAR(100),
    NOTES TEXT,
    UPDATE_BY VARCHAR(100),
    LOGTIME DATETIME
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_submodule (
    SUBMODULE_ID VARCHAR(10) PRIMARY KEY,
    SUBMODULE_NAME VARCHAR(100),
    NOTES TEXT,
    MODULE_ID VARCHAR(10),
    UPDATE_BY VARCHAR(100),
    LOGTIME DATETIME
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_member (
    MEMBER_REGISTRY VARCHAR(50) PRIMARY KEY,
    MEMBER_NO VARCHAR(50),
    MEMBER_NAME VARCHAR(200),
    MEMBER_EMAIL VARCHAR(200),
    ADDRESS_STAY TEXT,
    VILLAGE_ID VARCHAR(10),
    DISTRICT_ID VARCHAR(10),
    CITY_ID VARCHAR(10),
    MEMBER_STATUS_ID VARCHAR(10),
    ACTIVE_STATUS_ID INT,
    MEMBER_DATE_REGISTRY DATETIME,
    MEMBER_DATE_VERIFICATION DATETIME,
    BANKING_ACCOUNT_NO VARCHAR(100),
    member_management_id INT,
    LOGTIME DATETIME
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_member_management (
    MANAGEMENT_ID INT AUTO_INCREMENT PRIMARY KEY,
    MANAGEMENT_NAME VARCHAR(100)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_member_status (
    MEMBER_STATUS_ID VARCHAR(10) PRIMARY KEY,
    MEMBER_STATUS_NAME VARCHAR(100)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_village (
    VILLAGE_ID VARCHAR(10) PRIMARY KEY,
    VILLAGE_NAME VARCHAR(100),
    DISTRICT_ID VARCHAR(10)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_district (
    DISTRICT_ID VARCHAR(10) PRIMARY KEY,
    DISTRICT_NAME VARCHAR(100),
    CITY_ID VARCHAR(10)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_city (
    CITY_ID VARCHAR(10) PRIMARY KEY,
    CITY_NAME VARCHAR(100),
    TYPE_CITY_ID VARCHAR(10)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_type_city (
    TYPE_CITY_ID VARCHAR(10) PRIMARY KEY,
    TYPE_CITY_CODE VARCHAR(10),
    TYPE_CITY_NAME VARCHAR(100)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_images (
    IMAGE_ID INT AUTO_INCREMENT PRIMARY KEY,
    USER_ID VARCHAR(50),
    IMAGE_TYPE VARCHAR(50),
    IMAGE_FILE VARCHAR(500),
    LOGTIME DATETIME
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ma_member_address (
    ADDRESS_ID INT AUTO_INCREMENT PRIMARY KEY,
    MEMBER_REGISTRY VARCHAR(50),
    ADDRESS_STAY TEXT,
    VILLAGE_ID VARCHAR(10),
    DISTRICT_ID VARCHAR(10),
    CITY_ID VARCHAR(10)
) ENGINE=InnoDB;

