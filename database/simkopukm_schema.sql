-- ==================== LOAN TABLES ====================

CREATE TABLE IF NOT EXISTS mu_loan (
    LOAN_ID INT AUTO_INCREMENT PRIMARY KEY,
    MEMBER_REGISTRY VARCHAR(50),
    LOAN_PRODUCT_ID VARCHAR(20),
    LOAN_AMOUNT DECIMAL(15,2),
    LOAN_STATUS_ID INT,
