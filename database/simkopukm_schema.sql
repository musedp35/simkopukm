    LOGTIME DATETIME
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS mu_loan_account (
    LOAN_ACCOUNT_NO VARCHAR(50) PRIMARY KEY,
    MEMBER_REGISTRY VARCHAR(50),
    LOAN_PRODUCT_ID VARCHAR(20),
    LOAN_AMOUNT DECIMAL(15,2),
    REMAINING_AMOUNT DECIMAL(15,2),
    LOAN_STATUS_ID INT,
